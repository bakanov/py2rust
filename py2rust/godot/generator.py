def _rustfmt(content: bytes) -> bytes:
    result = subprocess.run(["rustfmt", "--edition", "2021"], input=content, capture_output=True, check=False)
    if result.returncode:
        raise GodotGenerationError(result.stderr.decode(errors="replace"))
    return result.stdout


def project_files(project: GodotProject) -> dict[str, bytes]:
    sources = _sources()
    files = {
        "Cargo.toml": _cargo(project).encode(),
        "lib.rs": _rustfmt(
            (
                GENERATED
                + "use godot::prelude::*;\n\n"
                + "".join(f"pub mod {name[:-3]};\n" for name in NATIVE_FILES)
                + "\npub struct OpenCiv3Native;\n\n#[gdextension]\nunsafe impl ExtensionLibrary for OpenCiv3Native {}\n"
            ).encode()
        ),
        "openciv3.gdextension": _gdextension(project).encode(),
    }
    files.update({name: _rustfmt(sources[name].encode()) for name in NATIVE_FILES})
    files["../native-modules.toml"] = _manifest().encode()
    return files


def generate_project(project: GodotProject, *, check: bool = False) -> list[Path]:
    if not project.root.joinpath("project.godot").is_file():
        raise GodotGenerationError(f"Not a Godot project: {project.root}")
    output = project.root / "native"
    files = project_files(project)
    differences = []
    for name, content in files.items():
        path = output / name
        if check and (not path.is_file() or path.read_bytes() != content):
            differences.append(str(path))
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
    if differences:
        raise GodotGenerationError("Generated files differ: " + ", ".join(sorted(differences)))
    return [output / name for name in files]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("root", type=Path)
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args()
    try:
        files = generate_project(GodotProject(arguments.root), check=arguments.check)
    except GodotGenerationError as error:
        parser.error(str(error))
    print(f"{'Verified' if arguments.check else 'Generated'} {len(files)} files")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
