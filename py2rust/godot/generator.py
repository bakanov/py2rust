def _media_source() -> str:
    return GENERATED + r"""use std::fmt::{Display, Formatter};

pub const MAX_IMAGE_BYTES: usize = 256 * 1024 * 1024;

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct MediaError(pub String);

impl Display for MediaError {
    fn fmt(&self, formatter: &mut Formatter<'_>) -> std::fmt::Result {
        formatter.write_str(&self.0)
    }
}

impl std::error::Error for MediaError {}

pub fn checked_image_bytes(width: usize, height: usize, channels: usize) -> Result<usize, MediaError> {
    let bytes = width
        .checked_mul(height)
        .and_then(|value| value.checked_mul(channels))
        .ok_or_else(|| MediaError("Image dimensions overflow".into()))?;
    if bytes == 0 || bytes > MAX_IMAGE_BYTES {
        return Err(MediaError("Image exceeds the native byte budget".into()));
    }
    Ok(bytes)
}

pub fn decode_pcx_rle(data: &[u8], expected: usize) -> Result<Vec<u8>, MediaError> {
    if expected > MAX_IMAGE_BYTES {
        return Err(MediaError("PCX output exceeds the native byte budget".into()));
    }
    let mut output = Vec::with_capacity(expected);
    let mut offset = 0;
    while offset < data.len() && output.len() < expected {
        let marker = data[offset];
        offset += 1;
        let (count, value) = if marker & 0xc0 == 0xc0 {
            if offset == data.len() {
                return Err(MediaError("Truncated PCX run".into()));
            }
            let count = usize::from(marker & 0x3f);
            let value = data[offset];
            offset += 1;
            (count, value)
        } else {
            (1, marker)
        };
        if count == 0 || output.len().saturating_add(count) > expected {
            return Err(MediaError("PCX run exceeds the expected output".into()));
        }
        output.resize(output.len() + count, value);
    }
    if output.len() != expected {
        return Err(MediaError("PCX output is shorter than expected".into()));
    }
    Ok(output)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn pcx_rle_is_bounded() {
        assert_eq!(decode_pcx_rle(&[0xc3, 7], 3).unwrap(), vec![7, 7, 7]);
        assert!(decode_pcx_rle(&[0xc3, 7], 2).is_err());
        assert!(decode_pcx_rle(&[0xc3], 3).is_err());
        assert!(checked_image_bytes(usize::MAX, 2, 4).is_err());
    }
}
"""


def _config_source() -> str:
    return GENERATED + r"""use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

pub fn parse_ini(source: &str) -> BTreeMap<(String, String), String> {
    let mut section = String::new();
    let mut values = BTreeMap::new();
    for original in source.lines() {
        let line = original.trim();
        if line.is_empty() || line.starts_with(';') || line.starts_with('#') {
            continue;
        }
        if line.starts_with('[') && line.ends_with(']') {
            section = line[1..line.len() - 1].trim().to_owned();
            continue;
        }
        if let Some((key, value)) = line.split_once('=') {
            values.insert((section.clone(), key.trim().to_owned()), value.trim().to_owned());
        }
    }
    values
}

pub fn case_insensitive_file(root: &Path, relative: &str) -> Option<PathBuf> {
    let direct = root.join(relative);
    if direct.is_file() {
        return Some(direct);
    }
    let mut current = root.to_path_buf();
    for part in Path::new(relative).components() {
        let name = part.as_os_str().to_string_lossy();
        let entries = current.read_dir().ok()?;
        let mut matches = entries.filter_map(Result::ok).filter(|entry| {
            entry.file_name().to_string_lossy().eq_ignore_ascii_case(&name)
        });
        let selected = matches.next()?;
        if matches.next().is_some() {
            return None;
        }
        current = selected.path();
    }
    current.is_file().then_some(current)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn ini_sections_and_comments_are_deterministic() {
        let values = parse_ini("; comment\n[locations]\n standalone = true \nvalue=2\n");
        assert_eq!(values.get(&("locations".into(), "standalone".into())).unwrap(), "true");
        assert_eq!(values.get(&("locations".into(), "value".into())).unwrap(), "2");
    }
}
"""


def _binary_source() -> str:
    return GENERATED + r"""use std::fmt::{Display, Formatter};

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct BinaryError(pub String);

impl Display for BinaryError {
    fn fmt(&self, formatter: &mut Formatter<'_>) -> std::fmt::Result {
        formatter.write_str(&self.0)
    }
}

impl std::error::Error for BinaryError {}

#[derive(Debug, Clone)]
pub struct BinaryReader<'a> {
    data: &'a [u8],
    offset: usize,
}

impl<'a> BinaryReader<'a> {
    pub fn new(data: &'a [u8]) -> Self {
        Self { data, offset: 0 }
    }

    pub fn position(&self) -> usize {
        self.offset
    }

    pub fn take(&mut self, count: usize) -> Result<&'a [u8], BinaryError> {
        let end = self.offset.checked_add(count).ok_or_else(|| BinaryError("Offset overflow".into()))?;
        if end > self.data.len() {
            return Err(BinaryError("Unexpected end of binary input".into()));
        }
        let value = &self.data[self.offset..end];
        self.offset = end;
        Ok(value)
    }

    pub fn u8(&mut self) -> Result<u8, BinaryError> {
        Ok(self.take(1)?[0])
    }

    pub fn i16_le(&mut self) -> Result<i16, BinaryError> {
        Ok(i16::from_le_bytes(self.take(2)?.try_into().unwrap()))
    }

    pub fn i32_le(&mut self) -> Result<i32, BinaryError> {
        Ok(i32::from_le_bytes(self.take(4)?.try_into().unwrap()))
    }

    pub fn i32_be(&mut self) -> Result<i32, BinaryError> {
        Ok(i32::from_be_bytes(self.take(4)?.try_into().unwrap()))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn reads_checked_endian_values() {
        let mut reader = BinaryReader::new(&[1, 2, 0, 3, 0, 0, 0]);
        assert_eq!(reader.u8().unwrap(), 1);
        assert_eq!(reader.i16_le().unwrap(), 2);
        assert_eq!(reader.i32_le().unwrap(), 3);
        assert!(reader.u8().is_err());
    }
}
"""


def _save_source() -> str:
    return GENERATED + r"""use std::fmt::{Display, Formatter};

pub const SAVE_MAGIC: &[u8; 8] = b"OPENCV3\0";
pub const SAVE_VERSION: u32 = 1;
pub const MAX_SAVE_BYTES: usize = 64 * 1024 * 1024;

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SaveError(pub String);

impl Display for SaveError {
    fn fmt(&self, formatter: &mut Formatter<'_>) -> std::fmt::Result {
        formatter.write_str(&self.0)
    }
}

impl std::error::Error for SaveError {}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct SaveEnvelope {
    pub version: u32,
    pub payload: Vec<u8>,
}

impl SaveEnvelope {
    pub fn encode(version: u32, payload: &[u8]) -> Result<Vec<u8>, SaveError> {
        if version == 0 || version > SAVE_VERSION || payload.len() > MAX_SAVE_BYTES {
            return Err(SaveError("Unsupported save version or size".into()));
        }
        let mut bytes = Vec::with_capacity(SAVE_MAGIC.len() + 4 + payload.len());
        bytes.extend_from_slice(SAVE_MAGIC);
        bytes.extend_from_slice(&version.to_le_bytes());
        bytes.extend_from_slice(payload);
        Ok(bytes)
    }

    pub fn decode(bytes: &[u8]) -> Result<Self, SaveError> {
        if bytes.len() > MAX_SAVE_BYTES || bytes.len() < SAVE_MAGIC.len() + 4 {
            return Err(SaveError("Invalid save size".into()));
        }
        if &bytes[..SAVE_MAGIC.len()] != SAVE_MAGIC {
            return Err(SaveError("Invalid save signature".into()));
        }
        let version = u32::from_le_bytes(bytes[SAVE_MAGIC.len()..SAVE_MAGIC.len() + 4].try_into().unwrap());
        if version == 0 || version > SAVE_VERSION {
            return Err(SaveError("Unsupported save version".into()));
        }
        Ok(Self { version, payload: bytes[SAVE_MAGIC.len() + 4..].to_vec() })
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn save_envelope_round_trip_and_validation() {
        let bytes = SaveEnvelope::encode(1, b"state").unwrap();
        assert_eq!(SaveEnvelope::decode(&bytes).unwrap().payload, b"state");
        assert!(SaveEnvelope::decode(b"bad").is_err());
        assert!(SaveEnvelope::encode(2, b"state").is_err());
    }
}
"""


