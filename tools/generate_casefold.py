"""Reproduce the pinned full default case-fold table from CPython's Unicode 15.1 reference."""

import unicodedata
from pathlib import Path


def generate() -> str:
    assert unicodedata.unidata_version == "15.1.0", "use the Python 3.13 Unicode 15.1 reference"
    mappings = []
    for codepoint in range(0x110000):
        if 0xD800 <= codepoint <= 0xDFFF:
            continue
        character = chr(codepoint)
        folded = character.casefold()
        if folded != character:
            value = "".join(f"\\u{{{ord(item):x}}}" for item in folded)
            mappings.append(f'    (0x{codepoint:x}, "{value}"),')
    assert len(mappings) == 1530
    return """//! Unicode 15.1 full default case folding, generated by tools/generate_casefold.py.
//! Reference: CPython 3.13 str.casefold(); includes expansions and excludes Turkic overrides.

pub fn casefold(text: &str) -> String {
    let mut result = String::with_capacity(text.len());
    for character in text.chars() {
        match MAPPINGS.binary_search_by_key(&(character as u32), |entry| entry.0) {
            Ok(index) => result.push_str(MAPPINGS[index].1),
            Err(_) => result.push(character),
        }
    }
    result
}

const MAPPINGS: &[(u32, &str)] = &[
""" + "\n".join(mappings) + "\n];\n"


if __name__ == "__main__":
    destination = Path(__file__).resolve().parents[1] / "py2rust/compiler/service_runtime/src/casefold.rs"
    destination.write_text(generate())
